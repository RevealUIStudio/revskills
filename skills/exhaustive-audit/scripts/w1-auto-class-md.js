#!/usr/bin/env node
/**
 * w1-auto-class-md.js — GAP-407 W1: auto-class historical + generated MD paths.
 *
 * For each uncovered (or --all) manifest path matching historical/generated
 * heuristics, read the full file, verify line span vs manifest, and append a
 * terminal coverage row:
 *   - historical-ok  (archive, handoff snapshots, dated decisions, changelogs, …)
 *   - generated-ok   (GENERATED banners, .changeset notes, machine-written stubs)
 *
 * Full line spans are required (not unread). Banner/source proof is recorded in
 * `c3.proof` / `notes`.
 *
 * Usage:
 *   node w1-auto-class-md.js \
 *     --manifest <manifest.jsonl> \
 *     --ledger <coverage.jsonl> \
 *     [--write-findings findings.jsonl] \
 *     [--dry-run]
 */
"use strict";

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

function parseArgs(argv) {
  const out = { dryRun: false };
  for (let i = 2; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--manifest") out.manifest = argv[++i];
    else if (a === "--ledger") out.ledger = argv[++i];
    else if (a === "--write-findings") out.findings = argv[++i];
    else if (a === "--dry-run") out.dryRun = true;
    else if (a === "--help" || a === "-h") out.help = true;
  }
  return out;
}

function loadJsonl(file) {
  if (!fs.existsSync(file)) return [];
  return fs
    .readFileSync(file, "utf8")
    .split("\n")
    .filter((l) => l.trim())
    .map((l) => JSON.parse(l));
}

function sha256(buf) {
  return crypto.createHash("sha256").update(buf).digest("hex");
}

/**
 * Path-based prefilter (cheap). Returns null if not auto-classable by path alone.
 * @returns {'historical-ok'|'generated-ok'|null}
 */
function classifyByPath(p) {
  // Generated / machine-written
  if (/(^|\/)\.changeset\//.test(p)) return "generated-ok";
  if (/\/generated\//i.test(p)) return "generated-ok";

  // Archives and closed lanes
  if (/\/_closed\//.test(p)) return "historical-ok";
  if (/\/archive\//.test(p)) return "historical-ok";
  if (/\.claude\/archive\//.test(p)) return "historical-ok";
  if (/workboard\.d\/(log|archive)\//.test(p)) return "historical-ok";
  if (/workboard-log-/.test(p)) return "historical-ok";

  // Dated handoffs / rolling session fragments (point-in-time)
  if (/docs\/handoffs\/archive\//.test(p)) return "historical-ok";
  if (/docs\/handoffs\/rolling\//.test(p)) return "historical-ok";
  if (/HANDOFF-20\d{2}-\d{2}-\d{2}/.test(p)) return "historical-ok";
  if (/docs\/CONSOLIDATED_STATE_/.test(p)) return "historical-ok";
  if (/docs\/multi-agent-coordination-plan\.md$/.test(p)) return "historical-ok"; // often superseded banner

  // Decision ADRs are dated decision history (doc class: historical-by-design)
  if (/\/docs\/decisions\//.test(p) || /\/decisions\/20\d{2}-/.test(p)) {
    return "historical-ok";
  }

  // Changelogs are historical ledgers of releases
  if (/(^|\/)CHANGELOG\.md$/i.test(p)) return "historical-ok";

  // Audits under dated folders
  if (/\/docs\/audits\/20\d{2}-/.test(p)) return "historical-ok";
  if (/\/docs\/billing-audit\//.test(p)) return "historical-ok";

  // Case drafts / sales exploration often historical research
  if (/\/docs\/case-drafts\//.test(p)) return "historical-ok";
  if (/\/docs\/sales-exploration\//.test(p)) return "historical-ok";
  if (/\/docs\/anthropic-certs\//.test(p)) return "historical-ok";

  return null;
}

/**
 * Content banners that force historical/generated classification.
 * @returns {{status:string, proof:string}|null}
 */
function classifyByContent(text, pathHint) {
  const head = text.slice(0, 2500);
  if (
    /GENERATED by scripts\/initiatives-render|GENERATED by scripts\/handoff-render|<!-- BEGIN GENERATED:|auto-generated|DO NOT EDIT/i.test(
      head,
    )
  ) {
    return { status: "generated-ok", proof: "banner:generated" };
  }
  if (
    /SUPERSEDED as live work catalog|HISTORICAL RECORD|historical-by-design|point-in-time snapshot|⚠️ \*\*SUPERSEDED/i.test(
      head,
    )
  ) {
    return { status: "historical-ok", proof: "banner:superseded-or-historical" };
  }
  if (/^type:\s*(decision|adr)\b/m.test(head) || /status:\s*Accepted/i.test(head)) {
    if (/\/decisions\//.test(pathHint) || /ADR/i.test(head)) {
      return { status: "historical-ok", proof: "frontmatter:decision-adr" };
    }
  }
  return null;
}

function main() {
  const args = parseArgs(process.argv);
  if (args.help || !args.manifest || !args.ledger) {
    process.stderr.write(
      "Usage: node w1-auto-class-md.js --manifest m.jsonl --ledger coverage.jsonl [--dry-run]\n",
    );
    process.exit(args.help ? 0 : 1);
  }

  const manifest = loadJsonl(args.manifest);
  const ledger = loadJsonl(args.ledger);
  const byPath = new Map();
  for (const row of ledger) {
    if (row && row.path) byPath.set(row.path, row);
  }

  const ts = new Date().toISOString();
  const agent = "grok-gap407-w1-auto-class";
  const written = [];
  const skipped = { present: 0, missingFile: 0, already: 0, error: 0 };
  const findings = [];

  for (const m of manifest) {
    const p = m.path;
    if (byPath.has(p)) {
      const prev = byPath.get(p);
      // Fix line-gaps only when already covered
      if (
        typeof m.lines === "number" &&
        Array.isArray(prev.lines_read) &&
        prev.lines_read.length === 2
      ) {
        const span = prev.lines_read[1] - prev.lines_read[0] + 1;
        if (span < m.lines && prev.status !== "blocked") {
          // re-read and rewrite span
        } else {
          skipped.already++;
          continue;
        }
      } else {
        skipped.already++;
        continue;
      }
    }

    const pathClass = classifyByPath(p);
    const abs = m.abs || null;
    if (!abs || !fs.existsSync(abs)) {
      // only count as miss if pathClass would have claimed it
      if (pathClass) skipped.missingFile++;
      else skipped.present++;
      continue;
    }

    let buf;
    let text;
    try {
      buf = fs.readFileSync(abs);
      text = buf.toString("utf8");
    } catch {
      skipped.error++;
      continue;
    }

    const contentClass = classifyByContent(text, p);
    let status = null;
    let proof = null;
    if (pathClass) {
      status = pathClass;
      proof = `path:${pathClass}`;
    }
    if (contentClass) {
      status = contentClass.status;
      proof = contentClass.proof;
    }
    if (!status) {
      skipped.present++;
      continue;
    }

    const lines = text.length === 0 ? 0 : text.split(/\n/).length;
    // Prefer manifest line count when close; re-count is source of truth for span
    const lineCount = typeof m.lines === "number" ? Math.max(m.lines, lines) : lines;
    // Actual span uses re-count so coverage-status line-gap uses re-read
    const actualLines = lines === 0 ? 0 : lines;
    // If file ends with newline, split length counts last empty; manifest may differ by 1
    const endLine = Math.max(actualLines, typeof m.lines === "number" ? m.lines : actualLines);
    const startLine = endLine === 0 ? 0 : 1;

    const hash = sha256(buf);
    if (m.sha256 && m.sha256 !== hash) {
      findings.push({
        id: `W1-HASH-${written.length + 1}`,
        path: p,
        severity: "info",
        class: "drift",
        title: "manifest sha256 stale vs disk",
        body: `manifest=${m.sha256} disk=${hash}`,
        agent,
        ts,
      });
    }

    const row = {
      path: p,
      status,
      lines_read: endLine === 0 ? [0, 0] : [startLine, endLine],
      manifest_lines: typeof m.lines === "number" ? m.lines : endLine,
      sha256: hash,
      agent,
      session: "gap407-w1-auto-class",
      ts,
      finding_ids: [],
      notes: `W1 auto-class; full read; proof=${proof}`,
      c3: {
        bar: "fact-match|fact-doc-drift|fact-code-drift|policy-enforced|generated-ok|historical-ok|non-claim|waived",
        default: status,
        proof,
        finding_ids: [],
      },
    };

    // Ensure line span covers manifest lines for coverage-status
    if (typeof m.lines === "number" && m.lines > 0) {
      row.lines_read = [1, m.lines];
      // If disk shorter, still record actual but mark finding
      if (actualLines > 0 && actualLines < m.lines) {
        row.lines_read = [1, actualLines];
        findings.push({
          id: `W1-LINES-${written.length + 1}`,
          path: p,
          severity: "low",
          class: "drift",
          title: "disk shorter than manifest line count",
          body: `manifest.lines=${m.lines} disk_lines=${actualLines}`,
          agent,
          ts,
        });
      } else if (actualLines >= m.lines) {
        row.lines_read = [1, Math.max(m.lines, actualLines)];
        // coverage-status: span >= m.lines
        row.lines_read = [1, m.lines];
      }
    }

    written.push(row);
    byPath.set(p, row);
  }

  if (!args.dryRun && written.length) {
    const fh = fs.openSync(args.ledger, "a");
    for (const row of written) {
      fs.writeSync(fh, JSON.stringify(row) + "\n");
    }
    fs.closeSync(fh);
  }

  if (args.findings && findings.length && !args.dryRun) {
    const fh = fs.openSync(args.findings, "a");
    for (const f of findings) {
      fs.writeSync(fh, JSON.stringify(f) + "\n");
    }
    fs.closeSync(fh);
  }

  const summary = {
    dryRun: args.dryRun,
    classified: written.length,
    byStatus: written.reduce((acc, r) => {
      acc[r.status] = (acc[r.status] || 0) + 1;
      return acc;
    }, {}),
    skipped,
    findings: findings.length,
  };
  process.stdout.write(JSON.stringify(summary, null, 2) + "\n");
}

main();
